    断言(os.path.exists(os.path.join(临时目录, "index.md")), "应生成 index.md 索引")

    # txt 内容应包含核心区块
    txt = open(paths["文本"], encoding="utf-8").read()
    断言("六爻排盘" in txt, "报告应含标题")
    断言("起卦时间" in txt, "报告应含起卦时间")
    断言("卦象" in txt, "报告应含卦象")
    断言("断卦要素" in txt, "报告应含断卦要素")
    断言(p_t.本卦 in txt, "报告应含本卦名")

    # JSON 结构与往返
    data = json.load(open(paths["JSON"], encoding="utf-8"))
    断言(data["卦象"]["本卦"] == p_t.本卦, "JSON 本卦应与盘一致")
    断言(data["卦象"]["变卦"] == p_t.变卦, "JSON 变卦应与盘一致")
    断言(len(data["卦象"]["六爻"]) == 6, "JSON 应有 6 爻")
    断言(data["起卦时间"]["日柱"], "JSON 应含日柱")
    断言(data["问事"]["所问"] == wq_t.问题, "JSON 应保留问事")
    断言(data["用神"]["主用神"] == "官鬼", "JSON 应含用神")
    断言(len(data["起卦"]["爻"]) == 6, "JSON 应含起卦过程六爻")
    # 每爻应含排盘要素
    for item in data["卦象"]["六爻"]:
        for k in ("爻位", "干支", "五行", "六亲", "六神", "世应", "空亡", "月破"):
            断言(k in item, f"爻记录缺少 {k}")

    # 序列化可完整还原起卦（种子可复现）
    断言(data["起卦"]["种子"] == 7, "应记录随机种子")
    复现 = 起卦(seed=data["起卦"]["种子"])
    断言(复现.本卦阴阳 == p_t.起卦.本卦阴阳, "同种子应复现同卦")
    断言(复现.变卦阴阳 == p_t.起卦.变卦阴阳, "同种子应变出同变卦")

    # 盘转字典：能被 json 完整序列化
    d2 = 盘转字典(p_t, wq_t, yong_t)
    try:
        json.dumps(d2, ensure_ascii=False)
        断言(True, "")
    except TypeError as e:
        断言(False, f"盘转字典不可序列化：{e}")

