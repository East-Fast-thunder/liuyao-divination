    paths2 = 保存记录(p_t, wq_t, yong_t, 存档目录=临时目录)
    断言(paths2["文本"] != paths["文本"], "同名占卜不应覆盖已有文件")
    断言(len(列出记录(临时目录)) == 2, "两次保存应有 2 条记录")

    # 列出记录：按时间倒序
    列表 = 列出记录(临时目录)
    断言(len(列表) == 2, "列出记录数量错误")
    断言(列表[0]["本卦"] == p_t.本卦, "记录应含本卦")

    # 读记录（按文件名）
    读回 = 读记录(os.path.basename(paths["JSON"]), 存档目录=临时目录)
    断言(读回 is not None and 读回["卦象"]["本卦"] == p_t.本卦, "读记录失败")

    # 索引文件包含记录
    idx = open(os.path.join(临时目录, "index.md"), encoding="utf-8").read()
    断言(p_t.本卦 in idx, "索引应包含本卦名")
    断言("共 2 条" in idx, "索引应统计条数")

    # 只保存文本
    目录3 = tempfile.mkdtemp(prefix="liuyao_txt_")
