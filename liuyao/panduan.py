def 十二长生位(爻五行: str, 地支: str) -> str:
    """
    以爻自体五行的长生起点、顺逆，求该支所处的十二长生状态。
    土随水行（简化：土长生在申，逆行）
    """
    start = 五行长生起点[爻五行]
    forward = 五行阳顺[爻五行]
    zhi_list = "子丑寅卯辰巳午未申酉戌亥"
    i0 = zhi_list.index(start)
    i = zhi_list.index(地支)
    offset = (i - i0) if forward else (i0 - i)
    return 十二长生[offset % 12]


def 入墓(爻五行: str, 墓支: str) -> bool:
    """爻之五行在墓支位置为墓库"""
    return 十二长生位(爻五行, 墓支) == "墓"


def 月建状态(爻: 爻盘, 月建: str, 日建: str) -> dict:
    info = {
        "长生": 十二长生位(爻.五行, 爻.干支[1]),
        "月令": 旺相休囚死(地支五行[月建], 爻.五行),
        "日辰": 旺相休囚死(地支五行[日建], 爻.五行),
        "月破": 六冲[爻.干支[1]] == 月建,
        "日冲": 六冲[爻.干支[1]] == 日建,
        "空亡": False,
    }
    # 入墓：该支在月日之墓库
    info["月墓"] = 入墓(爻.五行, 月建)
    info["日墓"] = 入墓(爻.五行, 日建)
    # 绝
    info["月绝"] = 十二长生位(爻.五行, 月建) == "绝"
    info["日绝"] = 十二长生位(爻.五行, 日建) == "绝"
    return info


