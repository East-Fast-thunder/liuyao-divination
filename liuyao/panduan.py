进神表 = {
    # 化进：同五行地支前进（阳动则进）
    ("寅", "卯"), ("巳", "午"), ("申", "酉"), ("亥", "子"),
    ("辰", "未"), ("未", "戌"), ("戌", "丑"), ("丑", "辰"),
}
退神表 = {(b, a) for a, b in 进神表}


def 动变关系(本爻: 爻盘) -> dict:
    """
    判断动爻与其变爻的关系。
    """
    if not 本爻.变爻:
        return {}
    b = 本爻.变爻
    ben_wx = 本爻.五行
    bian_wx = b["五行"]
    关系 = {}
    if 相生.get(bian_wx) == ben_wx:
        关系["回头生"] = f"变爻{bian_wx}生本爻{ben_wx}"
    if 相克.get(bian_wx) == ben_wx:
        关系["回头克"] = f"变爻{bian_wx}克本爻{ben_wx}"
    if 相生.get(ben_wx) == bian_wx:
        关系["化泄"] = f"本爻{ben_wx}生变爻{bian_wx}（化回头泄）"
    if 相克.get(ben_wx) == bian_wx:
        关系["化耗"] = f"本爻{ben_wx}克变爻{bian_wx}"
    bz = b["干支"][1]
    本支 = 本爻.干支[1]
    if (本支, bz) in 进神表:
        关系["化进神"] = f"{本支}→{bz}"
    if (本支, bz) in 退神表:
        关系["化退神"] = f"{本支}→{bz}"
    if 六冲[bz] == 本支:
        关系["化冲"] = f"变爻{bz}冲本爻{本支}（化反吟）"
    if 六合[bz] == 本支:
        关系["化合"] = f"变爻{bz}合本爻{本支}"
    if b["六亲"] == 本爻.六亲:
        关系["化同类"] = f"变爻同为{b['六亲']}"
    return 关系


# ---------------------------------------------------------------------------
# 五行生克 / 六亲关系
# ---------------------------------------------------------------------------

def 五行关系(a: str, b: str) -> str:
    """a 相对 b 的关系"""
    if a == b:
        return "同类（比和）"
    if 相生[a] == b:
        return f"{a}生{b}"
    if 相克[a] == b:
        return f"{a}克{b}"
    if 相生[b] == a:
        return f"{b}生{a}"
    if 相克[b] == a:
        return f"{b}克{a}"
    return "?"


def 世应关系(盘: 卦盘) -> dict:
    s, y = 盘.世, 盘.应
    return {
        "世": f"{s.干支} {s.六亲} {s.五行}",
        "应": f"{y.干支} {y.六亲} {y.五行}",
        "生克": 五行关系(s.五行, y.五行),
        "六冲": 六冲[s.干支[1]] == y.干支[1],
        "六合": 六合[s.干支[1]] == y.干支[1],
    }


# ---------------------------------------------------------------------------
# 卦内关系：冲合刑害
# ---------------------------------------------------------------------------

def 冲合关系(盘: 卦盘) -> List[str]:
    out = []
    zhis = [(y.爻位名, y.干支[1]) for y in 盘.六爻]
    for i in range(len(zhis)):
        for j in range(i + 1, len(zhis)):
            n1, z1 = zhis[i]
            n2, z2 = zhis[j]
            if 六冲[z1] == z2:
                out.append(f"{n1}{z1} 冲 {n2}{z2}")
            if 六合[z1] == z2:
                out.append(f"{n1}{z1} 合 {n2}{z2}")
            if 六害[z1] == z2:
                out.append(f"{n1}{z1} 害 {n2}{z2}")
            for grp in 三刑组:
                if z1 in grp and z2 in grp and z1 != z2:
                    out.append(f"{n1}{z1} 刑 {n2}{z2}")
    # 自刑
    for n, z in zhis:
        if z in 自刑:
            out.append(f"{n}{z} 自刑")
    return out


def 三合检查(盘: 卦盘, 额外: List[str] = None) -> List[str]:
    """检查三合局是否成立于卦中（含月日）"""
    all_z = [y.干支[1] for y in 盘.六爻]
    if 额外:
        all_z = all_z + list(额外)
    s = set(all_z)
    res = []
    for grp, wx in 三合局.items():
        gz = set(grp)
        if gz <= s:
            # 找对应地支
            res.append(f"{grp} 三合{wx}局")
        elif len(gz & s) == 2:
            res.append(f"{''.join(sorted(gz & s))} 半合{wx}局")
    return res


# ---------------------------------------------------------------------------
# 用神分析
# ---------------------------------------------------------------------------

def 分析用神(盘: 卦盘, 用: 用神信息) -> List[dict]:
    """
    分析用神：按优先级找用神爻，并给出旺衰、状态。
    """
    results = []
    for cand in 用.候选:
        if cand == "世爻":
            yao = 盘.世
            label = "世爻（代表自己）"
        elif cand == "应爻":
            yao = 盘.应
            label = "应爻（代表对方/环境）"
        elif cand == "用神":
            continue
        else:
            lst = 盘.按六亲(cand)
            if not lst:
                results.append({
                    "候选": cand,
                    "label": f"{cand}（卦中不现）",
                    "缺失": True,
                })
                continue
            yao = lst[0]
            label = f"{cand}爻"
        st = 月建状态(yao, 盘.时间.月建, 盘.时间.日建)
        results.append({
            "候选": cand,
            "label": label,
            "爻": yao,
            "旺衰": st,
            "动变": 动变关系(yao) if yao.动 else {},
            "空亡": yao.空亡,
            "月破": yao.月破,
            "世应": yao.世应,
        })
    return results


