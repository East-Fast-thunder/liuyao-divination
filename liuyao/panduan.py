# ---------------------------------------------------------------------------
# 旺衰：五行在月建的「五气」
# ---------------------------------------------------------------------------
# 以月建五行为基准：
#   与我同 → 旺
#   我生 → 相
#   生我 → 休
#   我克 → 囚
#   克我 → 死
# 这是传统「旺相休囚死」的算法之一（以月令为主）。

def 旺相休囚死(月建五行: str, 目标五行: str) -> str:
    if 月建五行 == 目标五行:
        return "旺"
    if 相生[月建五行] == 目标五行:      # 月令生我
        return "相"
    if 相生[目标五行] == 月建五行:      # 我生月令 → 泄
        return "休"
    if 相克[月建五行] == 目标五行:      # 我克月令 → 耗
        return "囚"
    if 相克[目标五行] == 月建五行:      # 月令克我
        return "死"
    return "?"


# 旺衰综合评级
旺衰等级 = {"旺": 4, "相": 3, "休": 2, "囚": 1, "死": 0}


def 综合旺衰(月建五行: str, 日建五行: str, 目标五行: str) -> dict:
    m = 旺相休囚死(月建五行, 目标五行)
    d = 旺相休囚死(日建五行, 目标五行)
    score = (旺衰等级[m] + 旺衰等级[d]) / 2
    if score >= 3.5:
        desc = "旺相有力"
    elif score >= 2.5:
        desc = "较旺"
    elif score >= 1.5:
        desc = "平稳偏弱"
    elif score >= 0.8:
        desc = "偏弱"
    else:
        desc = "休囚受制"
    return {"月令": m, "日辰": d, "评级": desc}


