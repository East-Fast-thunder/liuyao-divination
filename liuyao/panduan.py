# ---------------------------------------------------------------------------
# 汇总：整个盘的判断要素清单（只列要素，不下吉凶结论）
# ---------------------------------------------------------------------------

def 判断要素(盘: 卦盘, 用: 用神信息) -> dict:
    t = 盘.时间
    月建五 = 地支五行[t.月建]
    日建五 = 地支五行[t.日建]

    # 世应旺衰
    世衰 = 综合旺衰(月建五, 日建五, 盘.世.五行)
    应衰 = 综合旺衰(月建五, 日建五, 盘.应.五行)

    # 动爻汇总
    动爻分析 = []
    for y in 盘.动爻:
        item = {
            "爻位": y.爻位名,
            "六亲": y.六亲,
            "干支": y.干支,
            "动变": 动变关系(y),
            "变爻": y.变爻,
        }
        # 动爻与世爻关系
        item["对世"] = 五行关系(y.五行, 盘.世.五行)
        item["对用"] = 五行关系(y.五行,
                               盘.按六亲(用.主用神)[0].五行
                               if 盘.按六亲(用.主用神) else 盘.世.五行)
        动爻分析.append(item)

    return {
        "用神": 分析用神(盘, 用),
        "世应": 世应关系(盘),
        "世衰": 世衰,
        "应衰": 应衰,
        "动爻": 动爻分析,
        "冲合": 冲合关系(盘),
        "三合": 三合检查(盘, [t.月建, t.日建]),
        "空亡爻": [y.爻位名 + y.干支 for y in 盘.六爻 if y.空亡],
        "月破爻": [y.爻位名 + y.干支 for y in 盘.六爻 if y.月破],
        "伏神": 盘.伏神列表,
        "六神": 六神提示(盘),
    }
