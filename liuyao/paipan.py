def 卦象属性(卦盘obj: 卦盘) -> List[str]:
    """返回卦象的特征标签：六冲、六合、游魂、归魂、反吟、伏吟等"""
    tags = []
    名 = 卦盘obj.本卦
    if 名 in 六冲卦名:
        tags.append("六冲卦")
    if 名 in 六合卦名:
        tags.append("六合卦")
    if 卦盘obj.世卦 == "游魂":
        tags.append("游魂卦")
    if 卦盘obj.世卦 == "归魂":
        tags.append("归魂卦")
    if not 卦盘obj.有动爻:
        tags.append("静卦")
    return tags
