def 排盘(起卦结果: 起卦结果, 时间: 干支时间) -> 卦盘:
    """
    根据起卦结果与干支时间，排出完整六爻盘。
    """
    yao_list = 起卦结果.爻列表
    本卦阴阳 = 起卦结果.本卦阴阳
    变卦阴阳 = 起卦结果.变卦阴阳

    上卦, 下卦, 卦名 = 六爻成卦(本卦阴阳)
    宫, 世卦, 世爻序 = 查卦宫(卦名)
    应爻序 = ((世爻序 - 1 + 3) % 6) + 1

    宫五 = 卦五行[宫]

    # 变卦
    if 起卦结果.有动爻:
        变上, 变下, 变名 = 六爻成卦(变卦阴阳)
    else:
        变上 = 变下 = 变名 = None

    # 纳甲
    ganzi = 纳甲(上卦, 下卦)

    # 六神：按日干起（甲己起青龙…），自「初爻」往上顺排
    # 即：初爻=青龙、二爻=朱雀、三爻=勾陈、四爻=腾蛇、五爻=白虎、上爻=玄武
    日干 = 时间.日干
    起神 = 六神起法[日干]

    def 取六神(序号: int) -> str:
        return 六神序[(起神 + 序号 - 1) % 6]

    # 变爻纳甲：变卦的六爻纳甲
    if 变名:
        变纳甲 = 纳甲(变上, 变下)
    else:
        变纳甲 = None

    六爻列表: List[爻盘] = []
    for y in yao_list:
        seq = y.序号
        gz = ganzi[seq - 1]
        wx = 地支五行[gz[1]]
        liuqin = 六亲(宫五, wx)
        shiying = "世" if seq == 世爻序 else ("应" if seq == 应爻序 else "")

        # 空亡：爻支与日旬空亡相同
        kong = gz[1] in 时间.空亡
        # 月破：爻支与月建相冲
        po = 六冲_map(gz[1]) == 时间.月建

        # 变爻数据
        bian = None
        if y.动 and 变纳甲:
            bgz = 变纳甲[seq - 1]
            bwx = 地支五行[bgz[1]]
            bian = {
                "干支": bgz,
                "五行": bwx,
                "六亲": 六亲(宫五, bwx),
                "阴阳": y.变阳,
            }

        爻 = 爻盘(
            序号=seq,
            阴阳=y.阳,
            动=y.动,
            变阴阳=y.变阳,
            干支=gz,
            五行=wx,
            六亲=liuqin,
            六神=取六神(seq),
            世应=shiying,
            空亡=kong,
            月破=po,
            变爻=bian,
        )
        六爻列表.append(爻)

    # 伏神：本卦六亲不全时，用本宫首卦（八纯卦）补齐
    伏神列表 = 找伏神(宫, 六爻列表, ganzi)

    return 卦盘(
        起卦=起卦结果,
        时间=时间,
        本卦=卦名,
        上卦=上卦,
        下卦=下卦,
        变卦=变名,
        变上卦=变上,
        变下卦=变下,
        宫=宫,
        世卦=世卦,
        世爻=世爻序,
        应爻=应爻序,
        卦五行=宫五,
        六爻=六爻列表,
        伏神列表=伏神列表,
    )


def 六冲_map(zhi: str) -> str:
    from .ganzhi import 六冲
    return 六冲[zhi]


def 找伏神(宫: str, 六爻列表: List[爻盘], 本卦纳甲: Tuple[str, ...]) -> List[dict]:
    """
    伏神：若本卦某六亲不出现，则在本宫首卦（八纯卦）中找到该六亲所在爻，
    作为伏神，伏在该爻位下。

    返回列表，每项：
        {"伏爻": 爻序, "六亲": 六亲, "干支": 干支, "五行": 五行,
         "本位纳甲": 本位干支, "飞神六亲": 本卦该爻六亲}
    """
    宫五 = 卦五行[宫]
    已有六亲 = {y.六亲 for y in 六爻列表}
    缺 = [q for q in 六亲名 if q not in 已有六亲]
    if not 缺:
        return []

    纯卦名 = 宫
    纯纳甲 = 纳甲表[纯卦名]

    result = []
    for q in 缺:
        # 在八纯卦中找六亲为 q 的爻
        for i, gz in enumerate(纯纳甲):
            wx = 地支五行[gz[1]]
            if 六亲(宫五, wx) == q:
                # 该爻位对应的本卦爻
                本位 = 六爻列表[i]
                result.append({
                    "伏爻": i + 1,
                    "六亲": q,
                    "干支": gz,
                    "五行": wx,
                    "飞神六亲": 本位.六亲,
                    "飞神干支": 本位.干支,
                })
                break
    return result


