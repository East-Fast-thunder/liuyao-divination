def 纳甲(上卦: str, 下卦: str) -> Tuple[str, ...]:
    """
    给定上下经卦，返回六爻纳甲干支（初爻→上爻）。
    内卦三段取下卦的内纳甲，外卦三段取上卦的外纳甲。
    """
    inner = 经卦纳甲内[下卦]
    outer = 经卦纳甲外[上卦]
    return tuple(inner) + tuple(outer)


