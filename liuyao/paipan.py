@dataclass
class 爻盘:
    """排盘后单爻数据"""
    序号: int                 # 1-6
    阴阳: bool                # True=阳
    动: bool
    变阴阳: bool
    干支: str                 # 纳甲干支
    五行: str
    六亲: str
    六神: str
    世应: str                 # "世" / "应" / ""
    空亡: bool = False
    月破: bool = False
    伏神: Optional[dict] = None
    变爻: Optional[dict] = None   # 变爻数据

    @property
    def 爻位名(self) -> str:
        return ["初爻", "二爻", "三爻", "四爻", "五爻", "上爻"][self.序号 - 1]

    @property
    def 符号(self) -> str:
        # 6 行显示：阳爻实线，阴爻两段
        if self.阴阳:
            line = "▅▅▅▅▅"
        else:
            line = "▅▅ ▅▅"
        if self.动:
            mark = "○" if self.阴阳 else "✕"
            return f"{line}{mark}"
        return line + " "


@dataclass
class 卦盘:
    """完整六爻排盘结果"""
    起卦: 起卦结果
    时间: 干支时间
    本卦: str
    上卦: str
    下卦: str
    变卦: Optional[str]
    变上卦: Optional[str]
    变下卦: Optional[str]
    宫: str
    世卦: str                 # 六世/一世/…
    世爻: int                 # 世爻序号
    应爻: int                 # 应爻序号
    卦五行: str
    六爻: List[爻盘] = field(default_factory=list)
    伏神列表: List[dict] = field(default_factory=list)

    @property
    def 有动爻(self) -> bool:
        return self.起卦.有动爻

    @property
    def 动爻(self) -> List[爻盘]:
        return [y for y in self.六爻 if y.动]

    @property
    def 静爻(self) -> List[爻盘]:
        return [y for y in self.六爻 if not y.动]

    def 取爻(self, 序号: int) -> 爻盘:
        return self.六爻[序号 - 1]

    @property
    def 世(self) -> 爻盘:
        return self.取爻(self.世爻)

    @property
    def 应(self) -> 爻盘:
        return self.取爻(self.应爻)

    def 按六亲(self, 六亲名: str) -> List[爻盘]:
        return [y for y in self.六爻 if y.六亲 == 六亲名]


