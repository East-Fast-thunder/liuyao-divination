def 查卦宫(卦名: str) -> Tuple[str, str, int]:
    """
    查卦属于哪一宫、是第几世卦、世爻在第几爻。
    返回 (宫, 世卦名, 世爻序号)
    """
    for 宫, 卦序 in 八宫卦序.items():
        if 卦名 in 卦序:
            idx = 卦序.index(卦名)
            位 = 世位表[idx]
            return 宫, 位, 世爻数[位]
    raise ValueError(f"未知卦名：{卦名}")


