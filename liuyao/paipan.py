# 六冲卦：八纯卦 + 天雷无妄 + 雷天大壮（共 10 卦，六爻皆两两相冲）
六冲卦名 = {"乾", "坤", "震", "巽", "坎", "离", "艮", "兑", "无妄", "大壮"}
# 六合卦：六爻皆两两相合（八纯卦之外的传统「八合卦」核心六卦）
