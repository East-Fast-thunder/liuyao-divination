def 六亲(宫五行: str, 爻五行: str) -> str:
    """
    以卦宫五行为「我」，判断六亲：
        生我者父母，我生者子孙，同类者兄弟，我克者妻财，克我者官鬼
    注意「我克者妻财」「克我者官鬼」的主客体方向。
    """
    if 爻五行 == 宫五行:
        return "兄弟"
    if 相生.get(爻五行) == 宫五行:      # 爻五行 生 我（宫）
        return "父母"
    if 相生.get(宫五行) == 爻五行:      # 我 生 爻五行
        return "子孙"
    if 相克.get(宫五行) == 爻五行:      # 我 克 爻五行
        return "妻财"
    if 相克.get(爻五行) == 宫五行:      # 爻五行 克 我
        return "官鬼"
    raise ValueError(f"无法判断六亲：宫{宫五行} 爻{爻五行}")


