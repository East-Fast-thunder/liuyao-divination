# -*- coding: utf-8 -*-
"""
liuyao/wengua.py
================
问卦信息层：六爻很依赖「所问之事」是否明确

收集以下信息：
- 具体问题
- 问题类别（用于取用神）
- 与对方的关系定位
- 背景与时间范围
- 问自己 / 代问 / 问双方关系
- 是否有明确时限

并给出「问题是否适合问卦」的提示：
宿命化的问题（如"死之前能否在一起"）不适合六爻，会建议改成可操作问法。
"""

from __future__ import annotations

from dataclasses import dataclass, field, asdict
from typing import Dict, List, Optional


# 问题类别（与 panduan.用神表 保持一致）
问题类别列表 = [
    "财运钱财", "事业工作", "婚姻感情", "考试学业",
    "疾病健康", "出行远行", "诉讼官司", "房产置业",
    "求子", "寻人寻物", "综合",
]

# 提问主体
主体列表 = [
    "问自己", "问双方关系", "代问别人",
]

# 宿命化用词（过滤提示）
宿命词表 = [
    "一定", "注定", "命中", "死之前", "这辈子", "永远",
    "是不是没救了", "会不会死", "能不能活",
    "必然", "终究会", "逃不掉",
]


@dataclass
class 问事:
    问题: str = ""
    类别: str = "综合"
    主体: str = "问自己"
    关系定位: str = ""
    背景: str = ""
    时间范围: str = ""
    明确时限: str = ""

    def 转为字典(self) -> Dict[str, str]:
        return {
            "所问": self.问题,
            "类别": self.类别,
            "主体": self.主体,
            "关系定位": self.关系定位,
            "背景": self.背景,
            "时间范围": self.时间范围,
            "明确时限": self.明确时限,
        }


def 检查问题适合度(问事obj: 问事) -> List[str]:
    """
    返回提示列表。空列表代表问题基本适合。
    """
    tips = []
    q = 问事obj.问题.strip()

    if len(q) < 5:
        tips.append("问题描述过短，六爻要求所问之事明确，建议补充具体情境。")

    for w in 宿命词表:
        if w in q:
            tips.append(
                f"问题中出现「{w}」，属于宿命化/结果化提问。"
                f"六爻更适合问「当前阻力是什么、我能在哪些方面行动」，"
                f"而不是「注定如何」。建议改成可操作的问法。"
            )
            break

    if 问事obj.类别 == "综合":
        tips.append("未选择具体问题类别，取用神将按「世爻优先」处理，"
                    "建议后续选择更贴近的类别以提高排盘针对性。")

    if not 问事obj.时间范围 and not 问事obj.明确时限:
        tips.append("未提供时间范围。断卦的旺衰与应期判断依赖时间边界，"
                    "建议补充「未来一个月 / 三个月 / 今年内」等。")


    return tips


def 优化建议(问事obj: 问事) -> List[str]:
    """针对不同类别给出「问法改写」示例"""
    examples = {
        "财运钱财": "「未来三个月，我在X项目上的投入产出会呈现什么态势，主要风险点在哪？」",
        "事业工作": "「当前岗位的阻力主要来自哪里，我该聚焦提升哪方面？」",
        "婚姻感情": "「我和对方目前关系的主要阻力是什么，我能做哪些改善？」",
        "考试学业": "「这次考试我目前准备的薄弱环节在哪，接下来如何调整？」",
        "疾病健康": "「当前身体状态在近期需要重点关注什么，生活方式如何调整？」",
        "出行远行": "「这次行程在近期的主要不确定因素是什么？」",
        "诉讼官司": "「这件事的争议焦点在哪，我方需要注意什么？」",
        "房产置业": "「这次购房/置业决定在当前阶段的主要影响因素是什么？」",
        "求子": "「在身体与生活安排上，当前阶段需要重点关注什么？」",
        "寻人寻物": "「失物/失联方向在哪个区域可能性较大，可采取什么寻回措施？」",
        "综合": "「这件事目前的整体态势与我可采取的方向是什么？」",
    }
    return [examples.get(问事obj.类别, examples["综合"])]
